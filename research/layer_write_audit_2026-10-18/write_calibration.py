"""Show that apparently hidden aligned writes can arise from answer copying."""
import json
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent


def main():
    depth = np.linspace(0, 1, 29)
    beta = 0.05+4/(1+np.exp(-20*(depth-0.7)))
    u = np.array([1., 0., 0.])
    g = np.array([0., 1., 0.])
    answer = 0.1*g+np.sqrt(0.99)*np.array([0., 0., 1.])
    # Same surface-key lookup model as the earlier copying counterexample.
    active = 2*u+2*beta[:, None]*answer
    passive = -2*u+2*beta[:, None]*answer
    wa, wp = np.diff(active, axis=0), np.diff(passive, axis=0)
    cosine = lambda a, b: np.sum(a*b, axis=-1)/(np.linalg.norm(a, axis=-1)*np.linalg.norm(b, axis=-1))
    state_cos = cosine(active, passive)
    write_cos = cosine(wa, wp)
    wa_removed = wa-(wa@g)[:, None]*g
    wp_removed = wp-(wp@g)[:, None]*g
    removed_cos = cosine(wa_removed, wp_removed)
    assert state_cos[0] < -0.99 and state_cos[-1] > 0.88
    assert np.allclose(write_cos, 1) and np.allclose(removed_cos, 1)
    result = {
        "status": "exact_counterexample_not_llm_mechanism",
        "construction": "d_active=2u+2 beta_l v; d_passive=-2u+2 beta_l v. u and v are orthogonal. beta_l grows with depth. v is a distributed answer code generated by a surface-keyed lookup, not a stored pre-question role variable.",
        "state_cos": state_cos.tolist(), "write_cos": write_cos.tolist(),
        "write_cos_after_direct_readout_axis_removal": removed_cos.tolist(),
        "write_norms": np.linalg.norm(wa, axis=-1).tolist(),
        "conclusion": "Perfectly aligned updates can precede cumulative-state alignment even in the copying counterexample. Early update alignment alone would not identify semantic processing; tiny updates also make cosine misleading without magnitude and precision checks."
    }
    path = HERE/"WRITE_CALIBRATION.json"
    assert not path.exists(), "refusing overwrite"
    path.write_text(json.dumps(result, indent=2)+"\n")
    print("State cosine", state_cos[0], "to", state_cos[-1], "; update cosine", write_cos.min(), "to", write_cos.max())


if __name__ == "__main__":
    main()
